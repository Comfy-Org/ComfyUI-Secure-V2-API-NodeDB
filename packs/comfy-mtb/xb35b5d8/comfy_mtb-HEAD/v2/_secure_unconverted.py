class NotConvertedError(RuntimeError):
    """The node is registered for workflow loading only; it is not converted yet."""


def refusal(node_id):
    reason = REASONS.get(node_id)
    return f"{PACK}/{node_id} is not yet converted to Secure Nodes V2" + (f": {reason}" if reason else "")


