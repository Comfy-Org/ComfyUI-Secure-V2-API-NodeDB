"""Regenerate comfy_mtb v2/secure-nodes.json with the live encoder and prove the real loader accepts it.

Run in the gate container (run_in_gate.sh mounts the pack at /pack and the live overlay at /overlay):
  encode_manifest.py --write    -> /results/secure-nodes.json (+ /results/encode.json)
  encode_manifest.py --check    -> also require v2/secure-nodes.json to be byte-identical to the regenerated bytes
"""
import asyncio
import copy
import hashlib
import importlib.util
import json
import os
import shutil
import sys
import tempfile
from pathlib import Path

CORE = Path(os.environ.get("COMFY_CORE_ROOT", "/core"))
RESULTS = Path(os.environ.get("MTB_RESULTS", "/results"))
sys.path[:0] = [str(CORE), "/overlay"]

from comfy.cli_args import args  # noqa: E402

args.cpu = True
from comfy_secure_nodes import packdb, packmanifest, packruntime  # noqa: E402

# The original's ids, in its registration order, are _secure_unconverted.ORDER (from the gate freeze); 113 at the pin.
ORIGINAL_COUNT = 113


def pack_head() -> Path:
    root = Path(os.environ.get("MTB_PACK", "/pack"))
    if (root / "v2").is_dir():
        return root
    return next(d for d in sorted(root.rglob("v2")) if d.is_dir() and (d / "_secure_used.py").is_file()).parent


def load_v2(v2: Path):
    name = "comfy_mtb_v2_encode"
    spec = importlib.util.spec_from_file_location(name, v2 / "__init__.py", submodule_search_locations=[str(v2)])
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def build(classes, v2: Path):
    nodes = {}
    for cls in classes:
        schema = cls.GET_SCHEMA()
        schema.validate()
        node_id = schema.node_id
        methods = {key: key in cls.__dict__ for key in ("validate_inputs", "fingerprint_inputs", "check_lazy_status")}
        row = {
            "module": cls.__module__.split(".")[-1],
            "class": cls.__name__,
            "sdk_refs": bool(getattr(cls, "SDK_REFS", False)),
            "permissions": list(getattr(cls, "SDK_PERMISSIONS", ())),
            "methods": methods,
            "schema": packmanifest.encode_schema(copy.deepcopy(schema)),
        }
        if methods["validate_inputs"]:
            row["validation_inputs"] = packmanifest.encode_validation_inputs(cls)
        weights = packmanifest.encode_required_weights(cls)
        if weights:
            row["required_weights"] = weights
        nodes[node_id] = row
    return {"format": packmanifest.FORMAT, "runtime": packruntime.manifest_declaration(v2),
            "nodes": nodes, "web_directory": "web"}


def main(argv):
    head = pack_head()
    v2 = head / "v2"
    pack = load_v2(v2)
    ORIGINAL_IDS = list(sys.modules["comfy_mtb_v2_encode._secure_unconverted"].ORDER)
    assert len(ORIGINAL_IDS) == ORIGINAL_COUNT, len(ORIGINAL_IDS)
    extension = asyncio.run(pack.comfy_entrypoint())
    classes = asyncio.run(extension.get_node_list())
    ids = [cls.GET_SCHEMA().node_id for cls in classes]
    assert ids == ORIGINAL_IDS, ids
    assert list(pack.NODE_CLASS_MAPPINGS) == ORIGINAL_IDS
    manifest = build(classes, v2)
    data = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode("utf-8")
    # The real loader must accept every original id from these exact bytes.
    with tempfile.TemporaryDirectory(prefix="mtb-snap-") as tmp:
        snap = Path(tmp) / "comfy-mtb" / "xb35b5d8"
        folder = snap / (head.name if head.name != "pack" else "comfy_mtb-HEAD")
        shutil.copytree(head, folder, ignore=shutil.ignore_patterns("__pycache__"))
        (folder / "v2" / "secure-nodes.json").write_bytes(data)
        loaded = packdb.load_pack(snap, mount_name="custom_nodes.mtb_encode_check")
        registered = sorted(loaded.node_mappings)
        for node_id, proxy in loaded.node_mappings.items():
            assert proxy.GET_SCHEMA().node_id == node_id, node_id
        web = loaded.web_directory
    assert registered == sorted(ORIGINAL_IDS), registered
    report = {
        "encoder": {"module": packmanifest.__file__,
                    "sha256": hashlib.sha256(Path(packmanifest.__file__).read_bytes()).hexdigest()},
        "loader": {"module": packdb.__file__,
                   "sha256": hashlib.sha256(Path(packdb.__file__).read_bytes()).hexdigest()},
        "manifest_sha256": hashlib.sha256(data).hexdigest(),
        "node_ids": list(manifest["nodes"]),
        "loader_registered": registered,
        "loader_web_directory": None if web is None else str(web),
        "permissions": {k: v["permissions"] for k, v in manifest["nodes"].items()},
        "methods": {k: v["methods"] for k, v in manifest["nodes"].items()},
        "modules": sorted({v["module"] for v in manifest["nodes"].values()}),
    }
    if "--check" in argv:
        current = (v2 / "secure-nodes.json").read_bytes()
        report["committed_sha256"] = hashlib.sha256(current).hexdigest()
        report["committed_matches"] = current == data
        assert current == data, "v2/secure-nodes.json differs from the live-encoder output"
    RESULTS.mkdir(parents=True, exist_ok=True)
    if "--write" in argv:
        (RESULTS / "secure-nodes.json").write_bytes(data)
    (RESULTS / "encode.json").write_text(json.dumps(report, indent=2, sort_keys=True) + "\n")
    print(json.dumps(report, indent=1, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
