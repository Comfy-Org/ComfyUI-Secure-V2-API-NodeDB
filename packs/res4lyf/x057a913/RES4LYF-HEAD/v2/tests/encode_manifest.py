"""Regenerate v2/secure-nodes.json with the live encoder and prove the real loader accepts it (gate only).

  encode_manifest.py --write    -> /results/secure-nodes.json (+ /results/encode.json)
  encode_manifest.py --check    -> also require v2/secure-nodes.json to be byte-identical to the regenerated bytes
The manifest registers every frozen id, converted or refused by name. (The ids core registers itself are not
frozen; see test_core_ids.py.) It also carries the validate_inputs signature of each node that has one, and the
pack's scheduler providers (schedulers.py). test_res4lyf_schemas.py imports
``build`` and ``load_snapshot`` from here.
"""
import copy
import hashlib
import importlib
import importlib.util
import json
import os
import shutil
import sys
import tempfile
from pathlib import Path

CORE = Path(os.environ.get("COMFY_CORE_ROOT", "/core"))
PACK = Path(os.environ.get("RES4_PACK", "/pack"))
V2 = PACK / "v2"
RESULTS = Path(os.environ.get("RES4_RESULTS", "/results"))
for entry in (str(CORE), "/overlay"):
    if entry not in sys.path:
        sys.path.insert(0, entry)

from comfy.cli_args import args  # noqa: E402

args.cpu = True
from comfy_secure_nodes import packdb, packmanifest, packruntime, schedulerproviders  # noqa: E402

KEY = "x057a913"
# The guest dependency profile built from v2/pyproject.toml's exact pins (einops 0.8.2, scipy 1.18.1, tqdm 4.70.1;
# lock de02bb45). The manifest's runtime block declares it, so a production guest gets exactly these modules.
DEPENDENCY_PROFILE_SHA256 = "b90d9207bd8502c9cf235e120ed8e76c9372c682b3bc920483b4d9a8d1340e44"


def load_v2(name="res4lyf_v2_encode"):
    if name not in sys.modules:
        spec = importlib.util.spec_from_file_location(name, V2 / "__init__.py", submodule_search_locations=[str(V2)])
        module = importlib.util.module_from_spec(spec)
        sys.modules[name] = module
        spec.loader.exec_module(module)
    return sys.modules[name], importlib.import_module(f"{name}.schedulers")


def build(pack, schedulers):
    nodes = {}
    for node_id, cls in sorted(pack.NODE_CLASS_MAPPINGS.items()):
        schema = cls.GET_SCHEMA()
        schema.validate()
        assert schema.node_id == node_id, (schema.node_id, node_id)
        methods = {key: key in cls.__dict__ for key in ("check_lazy_status", "fingerprint_inputs", "validate_inputs")}
        row = {
            "class": cls.__name__,
            "methods": methods,
            "module": cls.__module__.split(".")[-1],
            "permissions": list(getattr(cls, "SDK_PERMISSIONS", ())),
            "schema": packmanifest.encode_schema(copy.deepcopy(schema)),
            "sdk_refs": bool(getattr(cls, "SDK_REFS", False)),
        }
        if methods["validate_inputs"]:
            row["validation_inputs"] = packmanifest.encode_validation_inputs(cls)
        weights = packmanifest.encode_required_weights(cls)
        if weights:
            row["required_weights"] = weights
        nodes[node_id] = row
    runtime = packruntime.manifest_declaration(V2, dependency_profile_sha256=DEPENDENCY_PROFILE_SHA256)
    return {"format": packmanifest.FORMAT, "nodes": nodes, "runtime": runtime,
            "scheduler_providers": schedulers.SCHEDULER_PROVIDERS}


def dump(manifest) -> bytes:
    return (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode("utf-8")


def load_snapshot(data: bytes, mount_name: str):
    """packdb.load_pack on a snapshot of v2 carrying exactly these manifest bytes, plus provider registration."""
    tmp = Path(tempfile.mkdtemp(prefix="res4lyf-snap-"))
    folder = tmp / "res4lyf" / KEY / PACK.name
    folder.mkdir(parents=True)
    shutil.copytree(V2, folder / "v2", ignore=shutil.ignore_patterns("__pycache__", "tests"))
    (folder / "v2" / "secure-nodes.json").write_bytes(data)
    loaded = packdb.load_pack(tmp / "res4lyf" / KEY, mount_name=mount_name)
    schedulerproviders.register(loaded)
    return loaded


def main(argv):
    pack, schedulers = load_v2()
    frozen_ids = sorted(json.loads((V2 / "_frozen_nodes.json").read_text())["nodes"])
    assert sorted(pack.NODE_CLASS_MAPPINGS) == frozen_ids, sorted(set(frozen_ids) ^ set(pack.NODE_CLASS_MAPPINGS))
    manifest = build(pack, schedulers)
    data = dump(manifest)
    loaded = load_snapshot(data, "custom_nodes.res4lyf_encode_check")
    registered = sorted(loaded.node_mappings)
    for node_id, proxy in loaded.node_mappings.items():
        assert proxy.GET_SCHEMA().node_id == node_id, node_id
    assert registered == frozen_ids, sorted(set(registered) ^ set(frozen_ids))
    validating = {k: v["validation_inputs"] for k, v in manifest["nodes"].items() if "validation_inputs" in v}
    report = {
        "encoder": {"module": packmanifest.__file__,
                    "sha256": hashlib.sha256(Path(packmanifest.__file__).read_bytes()).hexdigest()},
        "loader": {"module": packdb.__file__,
                   "sha256": hashlib.sha256(Path(packdb.__file__).read_bytes()).hexdigest()},
        "manifest_sha256": hashlib.sha256(data).hexdigest(),
        "nodes": len(manifest["nodes"]),
        "loader_registered": len(registered),
        "permissions": {k: v["permissions"] for k, v in manifest["nodes"].items() if v["permissions"]},
        "validate_inputs_nodes": len(validating),
        "validate_inputs_without_argument": sorted(k for k, v in manifest["nodes"].items()
                                                   if not v["methods"]["validate_inputs"]),
        "converted_validation": validating.get("ClownsharKSampler_Beta"),
        "scheduler_providers": [p.get("name") for p in manifest["scheduler_providers"]],
    }
    if "--check" in argv:
        current = (V2 / "secure-nodes.json").read_bytes()
        report["committed_sha256"] = hashlib.sha256(current).hexdigest()
        report["committed_matches"] = current == data
    RESULTS.mkdir(parents=True, exist_ok=True)
    if "--write" in argv:
        (RESULTS / "secure-nodes.json").write_bytes(data)
    (RESULTS / "encode.json").write_text(json.dumps(report, indent=2, sort_keys=True) + "\n")
    print(json.dumps(report, indent=1, sort_keys=True)[:6000])
    return 0 if report.get("committed_matches", True) else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
