"""Regenerate v2/secure-nodes.json with the live encoder and prove the real loader accepts it.

Run in the gate container (run_in_gate.sh mounts the pack at /pack and the overlay at /overlay):
  encode_manifest.py --write    -> /results/secure-nodes.json (+ /results/encode.json)
  encode_manifest.py --check    -> also require v2/secure-nodes.json to be byte-identical to the regenerated bytes
Rows keep this manifest's established shape: class, methods, module, permissions, the finalized schema
(GET_SCHEMA) and sdk_refs.
The established manifest predates Core's ``Schema.loop_boundary`` field; a ``loop_boundary`` of None (the
Schema default, and what every node here has) is left out so the served schema stays unchanged.
"""
import copy
import hashlib
import importlib.util
import json
import os
import shutil
import sys
import tempfile
from pathlib import Path

CORE = Path(os.environ.get("COMFY_CORE_ROOT", "/core"))
PACK = Path(os.environ.get("IMAGESAVER_PACK", "/pack"))
V2 = PACK / "v2"
RESULTS = Path(os.environ.get("IMAGESAVER_RESULTS", "/results"))
sys.path[:0] = [str(CORE), "/overlay"]

from comfy.cli_args import args  # noqa: E402

args.cpu = True
from comfy_secure_nodes import packdb, packmanifest, packruntime  # noqa: E402


def load_v2():
    name = "comfyui_image_saver_v2_encode"
    spec = importlib.util.spec_from_file_location(name, V2 / "__init__.py", submodule_search_locations=[str(V2)])
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def original_ids():
    """The original's NODE_CLASS_MAPPINGS keys, read from the pristine __init__.py as text (not imported)."""
    import ast
    tree = ast.parse((PACK / "__init__.py").read_text())
    for node in tree.body:
        target = node.target if isinstance(node, ast.AnnAssign) else (node.targets[0] if isinstance(node, ast.Assign) else None)
        if isinstance(target, ast.Name) and target.id == "NODE_CLASS_MAPPINGS":
            return [key.value for key in node.value.keys]
    raise AssertionError("NODE_CLASS_MAPPINGS not found in the pristine __init__.py")


def build(pack):
    nodes = {}
    for node_id, cls in sorted(pack.NODE_CLASS_MAPPINGS.items()):
        schema = cls.GET_SCHEMA()
        schema.validate()
        assert schema.node_id == node_id, (schema.node_id, node_id)
        assert not packmanifest.encode_required_weights(cls), node_id
        encoded = packmanifest.encode_schema(copy.deepcopy(schema))
        if "loop_boundary" in encoded["attrs"] and encoded["attrs"]["loop_boundary"] is None:
            del encoded["attrs"]["loop_boundary"]
        nodes[node_id] = {
            "class": cls.__name__,
            "methods": {key: key in cls.__dict__ for key in ("check_lazy_status", "fingerprint_inputs", "validate_inputs")},
            "module": cls.__module__.split(".")[-1],
            "permissions": list(getattr(cls, "SDK_PERMISSIONS", ())),
            "schema": encoded,
            "sdk_refs": bool(getattr(cls, "SDK_REFS", False)),
        }
    return {"format": packmanifest.FORMAT, "nodes": nodes, "runtime": packruntime.manifest_declaration(V2),
            "web_directory": "js"}


def main(argv):
    pack = load_v2()
    ids = original_ids()
    assert sorted(pack.NODE_CLASS_MAPPINGS) == sorted(ids), sorted(set(ids) ^ set(pack.NODE_CLASS_MAPPINGS))
    manifest = build(pack)
    data = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode("utf-8")
    # The real loader must accept every original id from these exact bytes.
    with tempfile.TemporaryDirectory(prefix="imagesaver-snap-") as tmp:
        snap = Path(tmp) / "comfyui-image-saver" / "x205d66a"
        folder = snap / PACK.name
        shutil.copytree(PACK, folder)
        (folder / "v2" / "secure-nodes.json").write_bytes(data)
        loaded = packdb.load_pack(snap, mount_name="custom_nodes.imagesaver_encode_check")
        registered = sorted(loaded.node_mappings)
        for node_id, proxy in loaded.node_mappings.items():
            assert proxy.GET_SCHEMA().node_id == node_id, node_id
    assert registered == sorted(ids), registered
    combo_outputs = {
        node_id: [{"index": index, "options": len(output["attrs"].get("options") or [])}
                  for index, output in enumerate(row["schema"]["outputs"]) if output["io_type"] == "COMBO"]
        for node_id, row in manifest["nodes"].items()
    }
    report = {
        "encoder": {"module": packmanifest.__file__,
                    "sha256": hashlib.sha256(Path(packmanifest.__file__).read_bytes()).hexdigest()},
        "loader": {"module": packdb.__file__,
                   "sha256": hashlib.sha256(Path(packdb.__file__).read_bytes()).hexdigest()},
        "manifest_sha256": hashlib.sha256(data).hexdigest(),
        "node_ids": list(manifest["nodes"]),
        "loader_registered": registered,
        "combo_outputs": {k: v for k, v in combo_outputs.items() if v},
    }
    if "--check" in argv:
        current = (V2 / "secure-nodes.json").read_bytes()
        report["committed_sha256"] = hashlib.sha256(current).hexdigest()
        report["committed_matches"] = current == data
    RESULTS.mkdir(parents=True, exist_ok=True)
    if "--write" in argv:
        (RESULTS / "secure-nodes.json").write_bytes(data)
    (RESULTS / "encode.json").write_text(json.dumps(report, indent=2, sort_keys=True) + "\n")
    print(json.dumps(report, indent=1, sort_keys=True))
    if "--check" in argv and not report["committed_matches"]:
        print("v2/secure-nodes.json differs from the live-encoder output", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
